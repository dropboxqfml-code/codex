POST_URL = "https://gall.dcinside.com/board/view/?id=worker_fixture&no=1"
POST_HEADER = {
    "title": "Synthetic worker post",
    "nickname": "fixture-author",
    "published_at_raw": "2026.11.14 10:20:30",
    "ip_display": None,
}


class PageView:
    """Delegate to a real fixture Page, overriding only its logical post URL.

    This is deliberately a test double, never an accepted production origin or
    a way to navigate to another site. Image currentSrc remains the real local
    HTTP URL, so the native saver and Chrome completion must match it exactly.
    """

    def __init__(self, page):
        self._page = page

    @property
    def url(self):
        return POST_URL

    def __getattr__(self, name):
        return getattr(self._page, name)


def fixture_assets(title):
    png = BytesIO()
    Image.new("RGB", (4, 3), "navy").save(png, format="PNG")
    gif = BytesIO()
    first = Image.new("RGB", (6, 4), "red")
    second = Image.new("RGB", (6, 4), "blue")
    first.save(
        gif,
        format="GIF",
        save_all=True,
        append_images=[second],
        duration=[100, 120],
        loop=0,
        optimize=False,
    )
    html = (
        '<!doctype html><html lang="en"><meta charset="utf-8">'
        f"<title>{title}</title>"
        "<style>body{margin:24px}.write_div img{display:block;width:240px;"
        "height:auto;margin:20px;image-rendering:pixelated}</style>"
        '<div class="gallview_head"><span class="title_subject">'
        f'{POST_HEADER["title"]}</span><div class="gall_writer" '
        f'data-nick="{POST_HEADER["nickname"]}"></div>'
        f'<span class="gall_date" title="{POST_HEADER["published_at_raw"]}">'
        f"{POST_HEADER['published_at_raw']}</span></div>"
        '<div class="appending_file">'
        '<a id="owned-png" href="#" data-original-name="declared-first.png">PNG</a>'
        '<a id="owned-gif" href="#" data-original-name="declared-animation.gif">GIF</a>'
        '</div><div class="write_div">'
        '<img src="/render-first.png" data-attachment-key="owned-png" alt="Owned PNG">'
        '<img src="/render-animation.gif" data-attachment-key="owned-gif" alt="Owned GIF">'
        '<img src="/render-first.png" data-attachment-key="owned-png" alt="Duplicate PNG">'
        '<span class="written_dccon"><img src="/render-first.png" '
        'alt="Excluded synthetic icon"></span></div></html>'
    ).encode()
    return {
        "/post": ("text/html; charset=utf-8", html),
        "/render-first.png": ("image/png", png.getvalue()),
        "/render-animation.gif": ("image/gif", gif.getvalue()),
    }


@contextmanager
def serve_fixtures(assets):
    """Serve fixed generated bytes on loopback; never proxy arbitrary URLs."""
    requested = []

    class Handler(BaseHTTPRequestHandler):
        def do_GET(self):
            requested.append(self.path)
            if self.path == "/favicon.ico":
                self.send_response(204)
                self.end_headers()
                return
            item = assets.get(self.path)
            if item is None:
                self.send_error(404)
                return
            content_type, payload = item
            self.send_response(200)
            self.send_header("Content-Type", content_type)
            self.send_header("Content-Length", str(len(payload)))
            self.send_header("Cache-Control", "no-store")
            self.end_headers()
            self.wfile.write(payload)

        def log_message(self, *_args):
            pass

    server = ThreadingHTTPServer(("127.0.0.1", 0), Handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    try:
        yield f"http://127.0.0.1:{server.server_port}", requested
    finally:
        server.shutdown()
        server.server_close()
        thread.join(timeout=5)
        assert not thread.is_alive(), "Owned fixture server did not stop"


def inspect_fixture(page, observed_at):
    """Use the real DOM observer scripts, explicitly trusting only this fixture."""
    root = page.locator(".write_div").element_handle()
    assert root is not None
    handles = []
    try:
        raw = root.evaluate(RAW_JS)
        handles = root.query_selector_all("img")
        for entry, image in zip(raw["images"], handles, strict=True):
            if not entry["excluded_reason"]:
                entry.update(image.evaluate(LOAD_JS, 15_000))
        return parse_snapshot(
            raw,
            expected_url=POST_URL,
            observed_at=observed_at,
            layout_status="fixture_validated",
        )
    finally:
        for handle in [*handles, root]:
            handle.dispose()


def bind_and_foreground_ci_window(process, page):
    """Activate only this test's unique window, using normal Windows activation."""
    from ctypes import wintypes

    deadline = time.monotonic() + 15
    while time.monotonic() < deadline:
        try:
            ui = WindowsUI(process.pid, page.title())
            break
        except NativeUIError:
            time.sleep(0.1)
    else:
        pytest.fail("The owned fixture browser could not be bound")
    page.bring_to_front()
    ui.user32.ShowWindow.argtypes = [wintypes.HWND, ui.ctypes.c_int]
    ui.user32.SetForegroundWindow.argtypes = [wintypes.HWND]
    ui.user32.ShowWindow(ui.target_hwnd, 9)
    ui.user32.SetForegroundWindow(ui.target_hwnd)
    deadline = time.monotonic() + 10
    while time.monotonic() < deadline:
        try:
            ui.assert_target_ready()
            return ui
        except NativeUIError:
            time.sleep(0.1)
    pytest.fail("The owned fixture browser did not receive CI foreground")


def wait_for_exclusive_saved_file(path, page, ui, timeout=15):
    """Require browser completion first, then inspect a local exclusive handle."""
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        ui.assert_target_ready()
        digest = exclusive_digest(path)
        if digest is not None:
            verified = verify_image(path, writer_finished=True).to_dict()
            assert verified["sha256"] == digest
            return digest, verified
        page.wait_for_timeout(100)
    pytest.fail("Completed owned download did not release its local writer")


def close_ci_browser(process, owned_process, created_at, browser_session, ui):
    """Bounded cleanup of the exact disposable CI process, including failed UI."""
    if process.poll() is not None:
        return
    if ui is not None and ui.user32.IsWindow(ui.target_hwnd):
        from ctypes import wintypes

        if ui._window_pid(ui.target_hwnd) in ui.process_ids():
            result = ui.ctypes.c_size_t()
            ui.user32.SendMessageTimeoutW.argtypes = [
                wintypes.HWND,
                wintypes.UINT,
                wintypes.WPARAM,
                wintypes.LPARAM,
                wintypes.UINT,
                wintypes.UINT,
                ui.ctypes.POINTER(ui.ctypes.c_size_t),
            ]
            ui.user32.SendMessageTimeoutW.restype = ui.ctypes.c_ssize_t
            # End only this owned window's menu loop; never issue a global key.
            ui.user32.SendMessageTimeoutW(
                ui.target_hwnd, 0x001F, 0, 0, 0x0002, 2_000, ui.ctypes.byref(result)
            )
    if browser_session is not None:
        try:
            browser_session.send("Browser.close", timeout=5_000)
        except Exception:
            pass  # A normal browser exit can disconnect before returning a reply.
        try:
            process.wait(timeout=10)
        except subprocess.TimeoutExpired:
            pass
    if process.poll() is None:
        # The only data belongs to this synthetic test. Never kill by image name
        # or terminate another browser. Production preserves uncertain saves.
        if owned_process.is_running() and owned_process.create_time() == created_at:
            owned_process.terminate()
            process.wait(timeout=10)
    assert process.poll() is not None, "Dedicated CI browser is still running"


def public_pipeline_notice(capsys, payload):
    text = json.dumps(payload, ensure_ascii=False)
    assert len(text.encode("utf-8")) < 2_000
    escaped = text.replace("%", "%25").replace("\r", "%0D").replace("\n", "%0A")
    with capsys.disabled():
        print(f"\n::notice title=Owned native post pipeline::{escaped}", flush=True)


def safe_fixture_save_dialog_snapshot(ui):
    """Read bounded type evidence only from this owned synthetic save dialog."""
    result = {"file_type_controls": []}
    if ui is None:
        return result
    suggested = ui.browser_suggested_filename
    result["suggested_is_text"] = isinstance(suggested, str)
    if isinstance(suggested, str):
        # This test has only generated loopback assets in a disposable profile.
        # Never report a directory even if the shell unexpectedly supplies one.
        result["suggested_basename"] = PureWindowsPath(suggested).name[:100]
        result["suggested_suffix"] = PureWindowsPath(suggested).suffix[:32]
        result["suggested_length"] = len(suggested)
    try:
        ui.assert_ready()
        hwnd = ui.user32.GetForegroundWindow()
        if (
            not hwnd
            or not ui.user32.IsWindow(hwnd)
            or ui._class_name(hwnd) != "#32770"
            or ui._window_pid(hwnd) not in ui.process_ids()
            or not ui.belongs_to_target(hwnd)
        ):
            result["owned_dialog_present"] = False
            return result
        result["owned_dialog_present"] = True
        dialog = ui.desktop.window(handle=hwnd).wrapper_object()
        combos = dialog.descendants(control_type="ComboBox")
        result["combo_automation_ids"] = [
            str(combo.element_info.automation_id)[:60] for combo in combos[:8]
        ]
        for combo in combos:
            automation_id = str(combo.element_info.automation_id)
            if automation_id not in {"FileTypeControlHost", "1136"}:
                continue
            if len(result["file_type_controls"]) >= 2:
                break
            ui.assert_control_ready(combo, dialog)
            entry = {
                "automation_id": automation_id,
                "role": combo.element_info.control_type,
                "class": combo.class_name()[:60],
                "window_text": combo.window_text()[:120],
            }
            result["file_type_controls"].append(entry)
            for name, read in (
                ("selected_text", combo.selected_text),
                ("value", lambda combo=combo: combo.iface_value.CurrentValue),
            ):
                try:
                    value = read()
                    entry[name] = value[:120] if isinstance(value, str) else None
                except Exception as error:
                    entry[name + "_error_type"] = type(error).__name__
    except Exception as error:
        result["diagnostic_error_type"] = type(error).__name__
    return result


def test_owned_chrome_pipeline_finalizes_two_unique_images_and_never_resaves(monkeypatch, capsys):
    import psutil
    import pywinauto  # noqa: F401
    from playwright.sync_api import sync_playwright

    # pywinauto's import-time stream can refer to a previous test's closed capsys.
    # Keep logging enabled and bind only this test's handlers to stable stderr.
    assert sys.__stderr__ is not None and not sys.__stderr__.closed
    for handler in logging.getLogger("pywinauto").handlers:
        if isinstance(handler, logging.StreamHandler) and not isinstance(
            handler, logging.FileHandler
        ):
            monkeypatch.setattr(handler, "stream", sys.__stderr__)

    title = "Image Monitor owned pipeline " + uuid.uuid4().hex
    assets = fixture_assets(title)
    # Keep final Windows paths within the production 240 UTF-16-unit budget.
    with (
        tempfile.TemporaryDirectory(prefix="imw-", dir=os.environ["RUNNER_TEMP"]) as directory,
        serve_fixtures(assets) as (origin, requested),
        NativeSaveLock(),
    ):
        root = Path(directory)
        database, save_root, profile = root / "q.sqlite", root / "images", root / "profile"
        profile.mkdir()
        process = subprocess.Popen(
            [
                str(browser_executable("chrome")),
                f"--user-data-dir={profile}",
                "--remote-debugging-port=0",
                "--remote-debugging-address=127.0.0.1",
                "--no-first-run",
                "--no-default-browser-check",
                "--disable-background-networking",
                "--force-renderer-accessibility",
                "--lang=en-US",
                "about:blank",
            ],
            stdout=subprocess.DEVNULL,
            stderr=subprocess.DEVNULL,
        )
        owned_process = psutil.Process(process.pid)
        created_at = owned_process.create_time()
        driver = cleanup_session = ui = None
        stage, artifacts, native_calls, native_names = "browser_startup", [], [], {}
        try:
            port = wait_for_debug_port(profile, process, timeout=30)
            driver = sync_playwright().start()
            browser = connect_owned_browser(driver, port)
            # Create before the first native modal menu/dialog can open.
            cleanup_session = browser.new_browser_cdp_session()
            context = browser.contexts[0]
            actual_page = context.pages[0] if context.pages else context.new_page()
            actual_page.goto(origin + "/post", wait_until="load", timeout=30_000)
            assert actual_page.url == origin + "/post"
            page = PageView(actual_page)
            now = datetime.now(UTC)
            snapshot = inspect_fixture(page, now)
            assert snapshot["queue_eligible"] is True
            assert snapshot["image_counts"] == {
                "body_occurrences": 4,
                "included_unique": 2,
                "excluded": 1,
                "pending": 0,
            }
            assert snapshot["images"][0]["occurrences"] == [1, 3]
            assert snapshot["excluded_images"][0]["reason"] == "body_dccon"
            ui = bind_and_foreground_ci_window(process, actual_page)
            original_save = native_body.save_body_image

            def counted_native_save(*args, **kwargs):
                native_calls.append(kwargs["image"]["stable_key"])
                return original_save(*args, **kwargs)

            monkeypatch.setattr(native_body, "save_body_image", counted_native_save)
            with QueueStore(database) as store:
                enqueue_snapshot(
                    store,
                    snapshot,
                    watch_name="fixture",
                    keyword="synthetic",
                    synthetic_fixture=True,
                )
                assert len(store.list_jobs()) == 2
                stage = "completion_reader_setup"
                # This production reader opens its owned background tab BEFORE
                # native input and must preserve source foreground throughout.
                with BrowserCompletion(browser, context, page, "chrome", ui=ui) as completion:
                    while (
                        job := store.claim_next("owned-ci-worker", datetime.now(UTC))
                    ) is not None:
                        source = job["source"]
                        assert source is not None
                        image = source["image"] | {"expected_header": POST_HEADER}
                        staging_directory = (
                            save_root / "_staging" / job["job_id"] / uuid.uuid4().hex
                        )
                        staging_directory.mkdir(parents=True)
                        store.transition(job["job_id"], job["lease_token"], "saving")
                        stage = "native_body_save"
                        saved = native_body.save_body_image(
                            page,
                            ui,
                            post_url=POST_URL,
                            image=image,
                            staging_directory=staging_directory,
                        )
                        native_names[image["stable_key"]] = saved["browser_suggested_filename"]
                        store.transition(job["job_id"], job["lease_token"], "verifying")
                        staging_file = Path(saved["staging_path"])
                        stage = "browser_completion"
                        evidence = completion.wait_for_completion(
                            staging_file, source["image"]["display_url"], ui, timeout=30
                        )
                        stage = "exclusive_local_verification"
                        digest, verification = wait_for_exclusive_saved_file(staging_file, page, ui)
                        assert (verification["width"], verification["height"]) == (
                            image["natural_width"],
                            image["natural_height"],
                        )
                        evidence["exclusive_sha256"] = digest
                        stage = "artifact_finalization"
                        artifact = finalize_saved_image(
                            store,
                            job["job_id"],
                            job["lease_token"],
                            observation_id=source["observation_id"],
                            save_root=save_root,
                            staging_file=staging_file,
                            verification=verification,
                            completion_evidence=evidence,
                            browser_suggested_filename=saved["browser_suggested_filename"],
                            saved_at=datetime.now(UTC),
                        )
                        assert artifact["phase"] == "finalized"
                        assert not staging_file.exists()
                        final_file = Path(artifact["final_path"])
                        # Fixture bytes/hashes are independent final assertions,
                        # never an input to production completion or native saving.
                        fixture_path = "/" + source["image"]["display_url"].rsplit("/", 1)[1]
                        expected_bytes = assets[fixture_path][1]
                        assert final_file.read_bytes() == expected_bytes
                        assert verification["sha256"] == hashlib.sha256(expected_bytes).hexdigest()
                        artifacts.append(artifact)
                assert len(artifacts) == len(native_calls) == 2
                assert len(set(native_calls)) == 2
                assert {job["status"] for job in store.list_jobs()} == {"completed"}
                assert store.claim_next("second-worker", datetime.now(UTC)) is None
                metadata_file = Path(artifacts[0]["metadata_path"])
                assert {artifact["metadata_path"] for artifact in artifacts} == {str(metadata_file)}
                metadata = json.loads(metadata_file.read_text(encoding="utf-8"))
                assert [image["status"] for image in metadata["images"]] == ["completed"] * 2
                assert metadata["post_metadata"]["title"] == POST_HEADER["title"]
                formats = []
                for entry in metadata["images"]:
                    artifact = entry["artifact"]
                    assert artifact["save_method"] == "native_context_menu_save_image_as"
                    assert artifact["completion"]["state"] == "COMPLETE"
                    assert artifact["completion"]["source_confirmed"] is True
                    assert artifact["completion"]["destination_confirmed"] is True
                    assert artifact["original_filename_match_status"] == "matched"
                    assert (
                        artifact["browser_suggested_filename"]
                        == native_names[artifact["stable_key"]]
                    )
                    if artifact["verification"]["detected_format"] == "PNG":
                        assert artifact["original_attachment_filename"] == "declared-first.png"
                        assert PureWindowsPath(artifact["browser_suggested_filename"]).name in {
                            "render-first",
                            "render-first.png",
                        }
                        assert artifact["saved_filename"] == "001.png"
                        assert artifact["occurrences"] == [1, 3]
                        assert artifact["verification"]["frames"] == 1
                    else:
                        assert artifact["verification"]["detected_format"] == "GIF"
                        assert artifact["original_attachment_filename"] == "declared-animation.gif"
                        assert PureWindowsPath(artifact["browser_suggested_filename"]).name in {
                            "render-animation",
                            "render-animation.gif",
                        }
                        assert artifact["saved_filename"] == "002.gif"
                        assert artifact["verification"]["frames"] == 2
                    formats.append(
                        {
                            "format": artifact["verification"]["detected_format"],
                            "frames": artifact["verification"]["frames"],
                        }
                    )
            stage = "browser_close"
            close_ci_browser(process, owned_process, created_at, cleanup_session, ui)
            assert process.poll() is not None
            stage = "local_only_recovery"
            metadata_before = metadata_file.read_bytes()

            def forbidden_native_save(*_args, **_kwargs):
                pytest.fail("Repeated observation/recovery attempted another native save")

            monkeypatch.setattr(native_body, "save_body_image", forbidden_native_save)
            with QueueStore(database) as store:
                # Rediscovery must also remain idempotent after a full DB reopen.
                repeated = snapshot | {"observed_at": (now + timedelta(seconds=1)).isoformat()}
                enqueue_snapshot(
                    store,
                    repeated,
                    watch_name="fixture",
                    keyword="synthetic",
                    synthetic_fixture=True,
                )
                assert store.claim_next("reopened-worker", datetime.now(UTC)) is None
                assert recover_finalizations(store, confirm_workers_stopped=True) == {
                    "recovered": 0,
                    "metadata_written": 0,
                    "skipped": 2,
                    "manual_review": [],
                }
                assert len(store.list_jobs()) == 2
                assert {job["status"] for job in store.list_jobs()} == {"completed"}
                assert metadata_file.read_bytes() == metadata_before
                assert len(native_calls) == 2
            assert set(requested) <= {*assets, "/favicon.ico"}
            public_pipeline_notice(
                capsys,
                {
                    "browser_kind": "chrome",
                    "fixture_origin": "loopback_generated_only",
                    "completed_count": 2,
                    "body_occurrences": 4,
                    "excluded_dccon_count": 1,
                    "duplicate_image_coalesced": True,
                    "source_correspondence": True,
                    "native_method": "native_context_menu_save_image_as",
                    "three_filenames_preserved": True,
                    "native_extensionless_suggestions_count": sum(
                        not PureWindowsPath(name).suffix for name in native_names.values()
                    ),
                    "formats": formats,
                    "recovery_no_gui": True,
                },
            )
        except Exception as error:
            public_pipeline_notice(
                capsys,
                {
                    "browser_kind": "chrome",
                    "stage": stage,
                    "error_type": type(error).__name__,
                    "native_calls": len(native_calls),
                    "finalized_count": len(artifacts),
                    "synthetic_save_dialog": safe_fixture_save_dialog_snapshot(ui),
                },
            )
            raise
        finally:
            already_failed = sys.exc_info()[0] is not None
            cleanup_errors = []
            try:
                close_ci_browser(process, owned_process, created_at, cleanup_session, ui)
            except Exception as error:
                cleanup_errors.append(type(error).__name__)
            if driver is not None:
                try:
                    driver.stop()
                except Exception as error:
                    cleanup_errors.append(type(error).__name__)
            if cleanup_errors:
                message = "Owned pipeline CI cleanup: " + ",".join(cleanup_errors)
                if already_failed:
                    with capsys.disabled():
                        print(f"\n::warning::{message}", flush=True)
                else:
                    pytest.fail(message)
